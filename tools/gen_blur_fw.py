#!/usr/bin/env python3
"""Generate driver/xlr8_blur_fw.h: the 64x64 divide-free blur as a C array for the V4L2 driver.

The two passes are stored back to back: interior at instruction 0, border at BASE2.
    gen_blur_fw.py > driver/xlr8_blur_fw.h
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import assemble  # noqa: E402


def build():
    W = H = 64
    p1, m1 = assemble.assemble(f".gen_blur {W} {H} nodiv\n.src 0x2000\n.dst 0x6000\n")[:2]
    p2, m2 = assemble.assemble(f".gen_blur_border {W} {H} nodiv\n.src 0x2000\n.dst 0x6000\n")[:2]
    return p1 + p2, len(p1), m1["threads"], m2["threads"]


def render():
    prog, base2, t1, t2 = build()
    out = ["/* SPDX-License-Identifier: GPL-2.0 */",
           "/* Generated by tools/gen_blur_fw.py from the divide-free 64x64 blur kernels. Do not edit. */",
           "#ifndef XLR8_BLUR_FW_H", "#define XLR8_BLUR_FW_H", "",
           f"#define XLR8_BLUR64_NPROG   {len(prog)}",
           f"#define XLR8_BLUR64_BASE2   {base2}     /* border pass starts here */",
           f"#define XLR8_BLUR64_THREADS1 {t1}       /* interior pixels */",
           f"#define XLR8_BLUR64_THREADS2 {t2}       /* border pixels */", "",
           "static const u16 xlr8_blur64_prog[XLR8_BLUR64_NPROG] = {"]
    for i in range(0, len(prog), 8):
        out.append("\t" + ", ".join(f"0x{w & 0xFFFF:04x}" for w in prog[i:i + 8]) + ",")
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(render())
