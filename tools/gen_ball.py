#!/usr/bin/env python3
"""Generate the ball kernel for a W x W frame (W a power of two, 2..256).

Same instruction sequence as sw/kernels/ball.asm with the x mask and y shift set from W.
Launch with W*W threads; parameter block at SRC, frame at DST (both given on the command line).
Valid domain: cx, cy in [-16384, 16383], r2 <= 2^30 (see ball_ref.py).

    gen_ball.py 128 --src 0x2000 --dst 0x2010 > sw/kernels/ball128.asm
"""
import argparse


def gen_args(w, dst):
    shift = w.bit_length() - 1
    return f"""; ball{w}_args.asm -- generated by tools/gen_ball.py {w} --args; {w}x{w} frame, one thread per pixel.
; Kernel arguments (preloaded by the hardware into r8..r12): ARG0 cx, ARG1 cy, ARG2 r2, ARG3 ball colour,
; ARG4 background colour. One bus transaction per pixel (the store); no parameter block in memory.
.threads {w * w}
.dst {dst:#x}
.text
    CONST r1, {w - 1}
    AND   r2, r0, r1
    CONST r3, {shift}
    SRL   r4, r0, r3
    SUB   r2, r2, r8
    SUB   r4, r4, r9
    MUL   r2, r2, r2
    MUL   r4, r4, r4
    ADD   r2, r2, r4
    SUB   r6, r10, r2
    CONST r5, 31
    SRL   r6, r6, r5
    CONST r5, 1
    SUB   r7, r5, r6
    MUL   r1, r11, r7
    MUL   r3, r12, r6
    ADD   r1, r1, r3
    STR   r1, r15, r0
    RET
"""


def gen(w, src, dst):
    if w < 2 or w > 256 or w & (w - 1):
        raise SystemExit("W must be a power of two between 2 and 256 (the mask and shift are CONST immediates)")
    shift = w.bit_length() - 1
    return f"""; ball{w}.asm -- generated by tools/gen_ball.py {w}; {w}x{w} frame, one thread per pixel.
; Parameter block at SRC: [0] cx [1] cy [2] r2 [3] ball colour [4] background colour.
.threads {w * w}
.src {src:#x}
.dst {dst:#x}
.text
    CONST r1, {w - 1}
    AND   r2, r0, r1
    CONST r3, {shift}
    SRL   r4, r0, r3
    CONST r5, 0
    LDR   r6, r14, r5
    CONST r5, 1
    LDR   r7, r14, r5
    SUB   r2, r2, r6
    SUB   r4, r4, r7
    MUL   r2, r2, r2
    MUL   r4, r4, r4
    ADD   r2, r2, r4
    CONST r5, 2
    LDR   r6, r14, r5
    SUB   r6, r6, r2
    CONST r5, 31
    SRL   r6, r6, r5
    CONST r5, 1
    SUB   r7, r5, r6
    CONST r5, 3
    LDR   r8, r14, r5
    CONST r5, 4
    LDR   r9, r14, r5
    MUL   r8, r8, r7
    MUL   r9, r9, r6
    ADD   r8, r8, r9
    STR   r8, r15, r0
    RET
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("w", type=int)
    ap.add_argument("--src", type=lambda s: int(s, 0), default=0x2000)
    ap.add_argument("--dst", type=lambda s: int(s, 0), default=0x2010)
    ap.add_argument("--args", action="store_true", help="arguments in r8..r12 instead of a parameter block")
    a = ap.parse_args()
    if a.args:
        if a.w < 2 or a.w > 256 or a.w & (a.w - 1):
            raise SystemExit("W must be a power of two between 2 and 256")
        print(gen_args(a.w, a.dst), end="")
    else:
        print(gen(a.w, a.src, a.dst), end="")
