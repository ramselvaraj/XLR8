#!/usr/bin/env python3
"""Generate the fixed-point Mandelbrot kernel for a W x W frame (W a power of two, 2..128).

Kernel arguments (registers r8..r10, set by the host per frame, so it can pan and zoom):
    ARG0 = x0   real part of the top-left corner, Q12 (two's complement)
    ARG1 = y0   imaginary part of the top-left corner, Q12
    ARG2 = step distance between pixels, Q12
Unrolled: 31 iterations of 20 instructions, about 650 instructions in all. See mandel_ref.py.

    gen_mandelbrot.py 128 --dst 0x2000 > sw/kernels/mandelbrot128.asm
"""
import argparse

ITERS = 31


def gen(w, dst, iters=ITERS):
    if w < 2 or w > 128 or w & (w - 1):
        raise SystemExit("W must be a power of two between 2 and 128")
    log = w.bit_length() - 1
    L = []
    a = L.append
    a(f"; mandelbrot{w}.asm -- generated by tools/gen_mandelbrot.py {w}; {w}x{w} frame, one thread per pixel.")
    a("; Fixed point Q12. ARG0 x0, ARG1 y0, ARG2 step (r8, r9, r10). Reference: tools/mandel_ref.py.")
    a(f".threads {w * w}")
    a(f".dst {dst:#x}")
    a(".text")
    a("    CONST r1, 12          ; Q12 shift")
    a("    CONST r2, 31          ; sign bit")
    a("    CONST r3, 1")
    a("    CONST r4, 64")
    a("    CONST r12, 8")
    a("    SLL   r4, r4, r12     ; 4.0 in Q12 = 16384")
    a(f"    CONST r12, {w - 1}")
    a("    AND   r5, r0, r12     ; x")
    a(f"    CONST r12, {log}")
    a("    SRL   r6, r0, r12     ; y")
    a("    MUL   r7, r5, r10     ; x*step")
    a("    ADD   r7, r7, r8      ; cr = x*step + x0")
    a("    MUL   r8, r6, r10     ; y*step")
    a("    ADD   r8, r8, r9      ; ci = y*step + y0")
    a("    SUB   r5, r5, r5      ; zr = 0")
    a("    SUB   r6, r6, r6      ; zi = 0")
    a("    CONST r9, 1           ; alive")
    a("    SUB   r10, r10, r10   ; count = 0")
    body = [
        "MUL   r11, r5, r5", "SRL   r11, r11, r1     ; a = zr^2",
        "MUL   r12, r6, r6", "SRL   r12, r12, r1     ; b = zi^2",
        "ADD   r13, r5, r6", "MUL   r13, r13, r13", "SRL   r13, r13, r1",
        "SUB   r13, r13, r11", "SUB   r13, r13, r12", "ADD   r13, r13, r8     ; new zi",
        "SUB   r5, r4, r11", "SUB   r5, r5, r12     ; 4.0 - |z|^2", "SRL   r5, r5, r2      ; outside",
        "SUB   r5, r3, r5      ; inside", "MUL   r9, r9, r5      ; alive stays 1 only while inside",
        "ADD   r10, r10, r9    ; count",
        "SUB   r11, r11, r12", "ADD   r11, r11, r7     ; new zr",
        "MUL   r5, r11, r9     ; freeze escaped points at 0", "MUL   r6, r13, r9",
    ]
    for i in range(iters):
        if i == 0:
            a("    ; --- iteration (repeated)")
        for line in body:
            a("    " + line)
    for line in ["CONST r1, 3", "SLL   r5, r10, r1      ; R = 8c", "CONST r13, 16", "SLL   r5, r5, r13",
                 "MUL   r6, r10, r10", "CONST r2, 2", "SRL   r6, r6, r2      ; G = c*c/4", "CONST r12, 8",
                 "SLL   r6, r6, r12", "OR    r5, r5, r6", "SLL   r7, r10, r2      ; 4c", "CONST r11, 64",
                 "ADD   r7, r7, r11     ; B = 4c + 64", "OR    r5, r5, r7",
                 "SUB   r9, r3, r9      ; 1 - alive: points that never escape are black", "MUL   r5, r5, r9",
                 "STR   r5, r15, r0", "RET"]:
        a("    " + line)
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("w", type=int)
    ap.add_argument("--dst", type=lambda s: int(s, 0), default=0x2000)
    a = ap.parse_args()
    print(gen(a.w, a.dst), end="")
