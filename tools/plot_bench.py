#!/usr/bin/env python3
"""Summarise results/bench/*.csv into tables (results/bench_tables.md) and two figures.

    plot_bench.py [results/bench]
"""
import csv
import glob
import os
import re
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

D = sys.argv[1] if len(sys.argv) > 1 else "results/bench"
OUT = os.path.dirname(D.rstrip("/")) or "."
WORK = ["ball64", "ball128", "ball256", "gradient64", "blur64"]
IMPLS = ["xlr8", "scalar", "neon", "numpy"]
LABEL = {"xlr8": "XLR8 GPU (50 MHz)", "scalar": "ARM scalar C", "neon": "ARM NEON", "numpy": "NumPy"}
# fixed categorical order from the reference palette: entity -> slot, never re-ranked
COLOR = {"xlr8": "#2a78d6", "scalar": "#eb6834", "neon": "#1baf7a", "numpy": "#eda100"}
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e6e5e1"
PS = 20.0   # ns per PL cycle at 50 MHz

data, cpu = {}, {}
for p in sorted(glob.glob(f"{D}/*_*.csv")):
    rows, meta = [], None
    for line in open(p):
        if line.startswith("#"):
            m = re.findall(r"(\w+)=([\d.]+)", line)
            meta = {k: float(v) for k, v in m}
        elif not line.startswith("impl"):
            rows.append(line.strip().split(","))
    if not rows:
        continue
    impl, work = rows[0][0], rows[0][1]
    a = np.array([[float(x) for x in r[3:]] for r in rows])
    data[(impl, work)] = a
    cpu[(impl, work)] = meta


def pct(x, q):
    return float(np.percentile(x, q))


def ms(x):
    return x / 1e6


lines = ["# Benchmark tables (generated by tools/plot_bench.py)", "",
         "## Frame time, milliseconds (median, and 5th to 95th percentile)", "",
         "| Workload | " + " | ".join(LABEL[i] for i in IMPLS) + " |", "|---|" + "---|" * len(IMPLS)]
for w in WORK:
    cells = []
    for i in IMPLS:
        a = data.get((i, w))
        if a is None:
            cells.append("n/a")
            continue
        t = a[:, 0]
        cells.append(f"{ms(pct(t, 50)):.3f} ({ms(pct(t, 5)):.3f} to {ms(pct(t, 95)):.3f})")
    lines.append(f"| {w} | " + " | ".join(cells) + " |")

lines += ["", "## CPU time used per frame, milliseconds (user + system, all frames including warmup)", "",
          "| Workload | " + " | ".join(LABEL[i] for i in IMPLS) + " |", "|---|" + "---|" * len(IMPLS)]
for w in WORK:
    cells = []
    for i in IMPLS:
        m = cpu.get((i, w))
        cells.append("n/a" if not m else f"{(m['cpu_user_ms'] + m['cpu_sys_ms']) / m['frames']:.3f} ({100 * (m['cpu_user_ms'] + m['cpu_sys_ms']) / m['wall_ms']:.0f}% of one core)")
    lines.append(f"| {w} | " + " | ".join(cells) + " |")

lines += ["", "## XLR8 time breakdown, microseconds (median)", "",
          "| Workload | total | prep | submit ioctl | GPU (CYCLES x 20 ns) | wait minus GPU (wakeup, overhead) | copy-out | CYCLES | bus xacts | stall cycles/xact |",
          "|---|---|---|---|---|---|---|---|---|---|"]
brk = {}
for w in WORK:
    a = data.get(("xlr8", w))
    if a is None:
        continue
    tot, prep, sub, wait, cp, cyc, xa, st = (np.median(a[:, k]) for k in range(8))
    gpu = cyc * PS
    brk[w] = (prep, sub, gpu, wait - gpu, cp, tot)
    lines.append(f"| {w} | {tot/1e3:.0f} | {prep/1e3:.1f} | {sub/1e3:.1f} | {gpu/1e3:.0f} | {(wait-gpu)/1e3:.0f} | {cp/1e3:.0f} | {cyc:.0f} | {xa:.0f} | {st/xa:.1f} |")

lines += ["", "## Speed relative to the XLR8 GPU (median frame time of the implementation divided by the GPU's)", "",
          "| Workload | " + " | ".join(LABEL[i] for i in IMPLS if i != "xlr8") + " |", "|---|" + "---|" * (len(IMPLS) - 1)]
for w in WORK:
    g = data.get(("xlr8", w))
    cells = []
    for i in IMPLS:
        if i == "xlr8":
            continue
        a = data.get((i, w))
        cells.append("n/a" if a is None or g is None else f"{np.median(a[:, 0]) / np.median(g[:, 0]):.3f}x")
    lines.append(f"| {w} | " + " | ".join(cells) + " |")
open(f"{OUT}/bench_tables.md", "w").write("\n".join(lines) + "\n")
print("\n".join(lines))

# ---------------------------------------------------------------- figure 1: frame time
plt.rcParams.update({"font.size": 10, "axes.edgecolor": GRID, "axes.labelcolor": MUTED, "text.color": INK,
                     "xtick.color": MUTED, "ytick.color": MUTED})


def fmt(v):
    return f"{v:.3g}" if v < 100 else f"{v:.0f}"


def style(ax):
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)


fig, ax = plt.subplots(figsize=(10, 5.2))
present = [w for w in WORK if any((i, w) in data for i in IMPLS)]
bw = 0.19
for k, i in enumerate(IMPLS):
    xs, med, lo, hi = [], [], [], []
    for j, w in enumerate(present):
        a = data.get((i, w))
        if a is None:
            continue
        t = ms(a[:, 0])
        xs.append(j + (k - 1.5) * (bw + 0.02))
        med.append(np.median(t)); lo.append(np.median(t) - np.percentile(t, 5)); hi.append(np.percentile(t, 95) - np.median(t))
    ax.bar(xs, med, bw, yerr=[lo, hi], color=COLOR[i], label=LABEL[i], error_kw={"ecolor": MUTED, "elinewidth": 1, "capsize": 2})
    for x, m in zip(xs, med):
        ax.text(x, m * 1.12, fmt(m), ha="center", va="bottom", fontsize=7.5, color=INK)
ax.set_yscale("log")
ax.set_ylim(0.01, 600)
ax.set_xticks(range(len(present)))
ax.set_xticklabels(present)
ax.set_ylabel("frame time, ms (median; log scale)")
style(ax)
ax.legend(frameon=False, ncol=4, loc="lower center", bbox_to_anchor=(0.5, -0.2), fontsize=9)
ax.set_title("Same frames, four implementations. PYNQ-Z2: Cortex-A9 at 650 MHz, XLR8 at 50 MHz", loc="left", fontsize=11)
fig.tight_layout()
fig.savefig(f"{D}/frame_time.png", dpi=150)

# ---------------------------------------------------------------- figure 2: CPU time per frame
fig, ax = plt.subplots(figsize=(10, 4.4))
pairs = [("scalar", "ARM scalar C computes the frame"), ("xlr8", "ARM drives the XLR8 GPU (ioctls, wakeup, copy-out)")]
cols = {"scalar": COLOR["scalar"], "xlr8": COLOR["xlr8"]}
for k, (i, lab) in enumerate(pairs):
    xs, vals = [], []
    for j, w in enumerate(present):
        m = cpu.get((i, w))
        if not m:
            continue
        xs.append(j + (k - 0.5) * 0.36)
        vals.append((m["cpu_user_ms"] + m["cpu_sys_ms"]) / m["frames"])
    ax.bar(xs, vals, 0.34, color=cols[i], label=lab)
    for x, v in zip(xs, vals):
        ax.text(x, v * 1.12, fmt(v), ha="center", va="bottom", fontsize=8, color=INK)
ax.set_yscale("log")
ax.set_ylim(0.01, 5)
ax.set_xticks(range(len(present)))
ax.set_xticklabels(present)
ax.set_ylabel("CPU time per frame, ms (log scale)")
style(ax)
ax.legend(frameon=False, ncol=2, loc="lower center", bbox_to_anchor=(0.5, -0.24), fontsize=9)
ax.set_title("What a frame costs the ARM: computing it, or driving the GPU", loc="left", fontsize=11)
fig.tight_layout()
fig.savefig(f"{D}/cpu_cost.png", dpi=150)
print("figures written to", D)
